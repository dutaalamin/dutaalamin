#!/usr/bin/env bash
# fetch-assets.sh - download generated profile images into assets/
# so README never fetches from a third-party server at render time (prevents 504).
# Self-authored assets (badge-*.svg, icon-*.svg) are committed, not fetched.
set -u
U="${GITHUB_USER:-dutaalamin}"
OUT="assets"
mkdir -p "$OUT"

dl() {
  local name="$1"; local url="$2"
  local min="${3:-400}"
  for i in 1 2 3; do
    if curl -sL --max-time 40 -o "$OUT/$name" "$url"; then
      local sz=$(wc -c < "$OUT/$name")
      # valid: is SVG, size >= min, and not an error page
      if head -c 120 "$OUT/$name" | grep -qiE "<svg|^<\?xml" \
         && [ "$sz" -ge "$min" ] \
         && ! grep -qiE "Something went wrong|Could not fetch|rate limit|429" "$OUT/$name"; then
        echo "OK  $name ($sz bytes)"
        return 0
      fi
    fi
    echo "retry $name ($i) - invalid/too small"
    sleep 4
  done
  echo "GAGAL $name (dibiarkan pakai versi lama)"
  return 1
}

dl views.svg "https://komarev.com/ghpvc/?username=$U&style=for-the-badge&color=555555&label=PROFILE+VIEWS"

# streak card, themed to match the dark card set
# cache-buster: the service caches per URL and serves stale counts for hours
dl streak-card.svg "https://github-readme-streak-stats-eight.vercel.app/?user=$U&theme=react&hide_border=true&background=0D1117&ring=58A6FF&fire=58A6FF&currStreakLabel=58A6FF&cb=$(date +%s)"

# pacman contribution graph is generated by pacman.yml into the `output` branch
dl pacman-dark.svg "https://raw.githubusercontent.com/$U/$U/output/pacman-contribution-graph-dark.svg"
dl pacman-light.svg "https://raw.githubusercontent.com/$U/$U/output/pacman-contribution-graph.svg"

echo "--- selesai ---"
ls -la "$OUT"
